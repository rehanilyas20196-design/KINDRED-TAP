-- 009_therapist_portal.sql
-- Therapist portal: caseload, treatment plans, session notes, homework,
-- notifications and message read receipts.
--
-- Every clinical table added here is scoped twice - by the therapist who owns
-- the record and by the client it is about - so an id lifted out of a URL
-- cannot be used to read another practitioner's caseload. The API enforces
-- both on every read and write; these constraints are the second line.

-- =============================================================================
-- client_cases - the therapist's caseload
-- =============================================================================
-- A row exists when a therapeutic relationship exists. It is created when the
-- therapist opens a client from their diary, and the API also treats anybody
-- with a session, a conversation or a plan together as part of the caseload,
-- so a case row is never the only way in.
CREATE TABLE IF NOT EXISTS client_cases (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  therapist_id UUID       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  client_id   UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  status      TEXT        NOT NULL DEFAULT 'active'
              CHECK (status IN ('active', 'paused', 'completed', 'archived')),
  opened_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  closed_at   TIMESTAMPTZ,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT client_cases_pair_uniq UNIQUE (therapist_id, client_id),
  CONSTRAINT client_cases_distinct CHECK (therapist_id <> client_id)
);

CREATE INDEX IF NOT EXISTS client_cases_therapist_idx
  ON client_cases (therapist_id, status, updated_at DESC);
CREATE INDEX IF NOT EXISTS client_cases_client_idx ON client_cases (client_id);

-- =============================================================================
-- Treatment plans: plan -> goals -> objectives
-- =============================================================================
-- Nothing here is a diagnosis or a recommendation generated by the system.
-- A therapist writes every row; the schema only records what they chose to
-- write, when it is due and how far along they judge it to be.
CREATE TABLE IF NOT EXISTS treatment_plans (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  therapist_id UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  client_id    UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title        TEXT        NOT NULL,
  summary      TEXT,
  status       TEXT        NOT NULL DEFAULT 'draft'
               CHECK (status IN ('draft', 'active', 'completed', 'archived')),
  start_date   DATE,
  target_date  DATE,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS treatment_plans_therapist_idx
  ON treatment_plans (therapist_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS treatment_plans_client_idx
  ON treatment_plans (client_id, status);

CREATE TABLE IF NOT EXISTS treatment_goals (
  id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  plan_id          UUID        NOT NULL REFERENCES treatment_plans(id) ON DELETE CASCADE,
  therapist_id     UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  position         INTEGER     NOT NULL DEFAULT 0,
  title            TEXT        NOT NULL,
  notes            TEXT,
  status           TEXT        NOT NULL DEFAULT 'in_progress'
                   CHECK (status IN ('not_started', 'in_progress', 'completed', 'dropped')),
  target_date      DATE,
  progress_percent INTEGER     NOT NULL DEFAULT 0
                   CHECK (progress_percent BETWEEN 0 AND 100),
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS treatment_goals_plan_idx
  ON treatment_goals (plan_id, position);

CREATE TABLE IF NOT EXISTS treatment_objectives (
  id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  goal_id       UUID        NOT NULL REFERENCES treatment_goals(id) ON DELETE CASCADE,
  therapist_id  UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  position      INTEGER     NOT NULL DEFAULT 0,
  title         TEXT        NOT NULL,
  -- Free-form intervention labels the therapist typed ("CBT", "breathing
  -- exercises", "cognitive restructuring"). Data, never generated content.
  interventions JSONB       NOT NULL DEFAULT '[]'::jsonb,
  status        TEXT        NOT NULL DEFAULT 'not_started'
                CHECK (status IN ('not_started', 'in_progress', 'completed', 'dropped')),
  target_date   DATE,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS treatment_objectives_goal_idx
  ON treatment_objectives (goal_id, position);

-- =============================================================================
-- session_notes - the clinical record of one session
-- =============================================================================
-- Therapist-only. Nothing in this table is ever returned to a client account:
-- the routes that read it require the therapist who wrote it. `private_notes`
-- is explicitly the practitioner's own memo; `client_summary` plus
-- `shared_with_client` is the part deliberately written for the client to see.
CREATE TABLE IF NOT EXISTS session_notes (
  id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  session_id         UUID        NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
  therapist_id       UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  client_id          UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  status             TEXT        NOT NULL DEFAULT 'draft'
                     CHECK (status IN ('draft', 'final')),
  session_date       DATE        NOT NULL DEFAULT CURRENT_DATE,
  session_number     INTEGER     CHECK (session_number IS NULL OR session_number > 0),
  session_type       TEXT,
  presentation       TEXT,
  discussion          TEXT,
  interventions      TEXT,
  client_response    TEXT,
  progress_notes     TEXT,
  homework           TEXT,
  next_session_plan  TEXT,
  private_notes      TEXT,
  client_summary     TEXT,
  shared_with_client BOOLEAN     NOT NULL DEFAULT false,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT session_notes_session_uniq UNIQUE (session_id)
);

CREATE INDEX IF NOT EXISTS session_notes_therapist_idx
  ON session_notes (therapist_id, session_date DESC);
CREATE INDEX IF NOT EXISTS session_notes_client_idx
  ON session_notes (client_id, session_date DESC);

-- =============================================================================
-- homework_items - between-session tasks and whether they were done
-- =============================================================================
CREATE TABLE IF NOT EXISTS homework_items (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  therapist_id UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  client_id    UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  session_id   UUID        REFERENCES sessions(id) ON DELETE SET NULL,
  title        TEXT        NOT NULL,
  details      TEXT,
  status       TEXT        NOT NULL DEFAULT 'assigned'
               CHECK (status IN ('assigned', 'in_progress', 'completed', 'skipped')),
  due_date     DATE,
  completed_at TIMESTAMPTZ,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS homework_therapist_idx
  ON homework_items (therapist_id, created_at DESC);
CREATE INDEX IF NOT EXISTS homework_client_idx
  ON homework_items (client_id, status);

-- =============================================================================
-- notifications - activity for the signed-in practitioner
-- =============================================================================
-- Rows are addressed to one user and are only ever read with that user's id in
-- the WHERE clause, so a notification id in a URL cannot be marked read on
-- somebody else's behalf.
CREATE TABLE IF NOT EXISTS notifications (
  id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id    UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  type       TEXT        NOT NULL,
  title      TEXT        NOT NULL,
  body       TEXT,
  link       TEXT,
  data       JSONB       NOT NULL DEFAULT '{}'::jsonb,
  read_at    TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS notifications_user_idx
  ON notifications (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS notifications_unread_idx
  ON notifications (user_id, read_at);

-- =============================================================================
-- message_reads - what each participant has actually seen
-- =============================================================================
-- A conversation has no read state of its own: two people read it at two
-- different speeds, so the marker belongs to the reader.
CREATE TABLE IF NOT EXISTS message_reads (
  user_id        UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  conversation_id UUID       NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  last_read_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, conversation_id)
);

-- =============================================================================
-- Additive columns on tables that already exist
-- =============================================================================
-- `confirmed_at`: a booking arrives scheduled from the client's side; the
-- therapist accepting it is what turns it into an appointment. Adding a
-- column rather than a new status keeps the diary CHECK constraints, the user
-- portal and every existing session query exactly as they are.
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS confirmed_at TIMESTAMPTZ;

-- Whether a result has been opened by the practitioner, so "pending
-- assessments" means "not yet reviewed" rather than a guess.
ALTER TABLE assessment_results ADD COLUMN IF NOT EXISTS reviewed_at TIMESTAMPTZ;

-- Therapist availability and notification preferences live on the profile row
-- so the directory, settings and calendar all read one place.
ALTER TABLE therapist_profiles ADD COLUMN IF NOT EXISTS availability_days JSONB NOT NULL DEFAULT '[]'::jsonb;
ALTER TABLE therapist_profiles ADD COLUMN IF NOT EXISTS availability_hours TEXT;
ALTER TABLE therapist_profiles ADD COLUMN IF NOT EXISTS notification_prefs JSONB NOT NULL DEFAULT '{}'::jsonb;

-- =============================================================================
-- updated_at triggers
-- =============================================================================
CREATE OR REPLACE FUNCTION touch_updated_at() RETURNS trigger AS $$
  BEGIN NEW.updated_at = now(); RETURN NEW; END;
$$ LANGUAGE plpgsql;

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'client_cases', 'treatment_plans', 'treatment_goals', 'treatment_objectives',
    'session_notes', 'homework_items'
  ] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS %I ON %I', t || '_touch', t);
    EXECUTE format(
      'CREATE TRIGGER %I BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION touch_updated_at()',
      t || '_touch', t);
  END LOOP;
END $$;

-- =============================================================================
-- Row Level Security
-- =============================================================================
-- Enabled with no policies: these tables hold session notes and treatment
-- plans. The API connects as the table owner and keeps working; direct browser
-- access through the Supabase anon key is denied outright.
ALTER TABLE client_cases          ENABLE ROW LEVEL SECURITY;
ALTER TABLE treatment_plans       ENABLE ROW LEVEL SECURITY;
ALTER TABLE treatment_goals       ENABLE ROW LEVEL SECURITY;
ALTER TABLE treatment_objectives  ENABLE ROW LEVEL SECURITY;
ALTER TABLE session_notes         ENABLE ROW LEVEL SECURITY;
ALTER TABLE homework_items        ENABLE ROW LEVEL SECURITY;
ALTER TABLE notifications         ENABLE ROW LEVEL SECURITY;
ALTER TABLE message_reads         ENABLE ROW LEVEL SECURITY;
